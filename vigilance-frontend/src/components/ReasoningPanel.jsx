function tierClass(t) {
  return String(t || "").toLowerCase();
}

/** Highlight [E123] evidence ids in explanation text */
function formatExplanation(text) {
  if (!text) return null;
  const parts = text.split(/(\[E\d+\])/g);
  return parts.map((p, i) =>
    /^\[E\d+\]$/.test(p) ? (
      <span className="eid" key={i}>
        {p}
      </span>
    ) : (
      <span key={i}>{p}</span>
    )
  );
}

export default function ReasoningPanel({ company, reasoning }) {
  const r = reasoning;
  return (
    <div className="panel">
      <div className="panel-h">
        <h3>
          Reasoning &amp; recommendation <span>{company.symbol}</span>
        </h3>
        <button className="btn">Regenerate</button>
      </div>

      <div className="metric-row">
        <div className="metric">
          <label>Composite score</label>
          <div className={`big ${r.composite_score >= 70 ? "red" : ""}`}>
            {Number(r.composite_score).toFixed(1)}
          </div>
        </div>
        <div className="metric">
          <label>Risk tier</label>
          <div style={{ marginTop: 6 }}>
            <span className={`tier ${tierClass(r.risk_tier)}`} style={{ fontSize: 14, padding: "6px 12px" }}>
              {String(r.risk_tier).toUpperCase()}
            </span>
          </div>
        </div>
        <div className="metric">
          <label>Model P(risk)</label>
          <div className="big cyan">{Number(r.model_probability).toFixed(3)}</div>
        </div>
      </div>

      <div className="section-title">Top model drivers</div>
      <div className="drivers">
        {(r.top_drivers || []).map((d) => (
          <span className="driver-chip" key={d.feature}>
            <strong>{d.feature.replace(/^.*__/, "")}</strong>
            {" · "}
            {(d.importance * 100).toFixed(1)}%
          </span>
        ))}
      </div>

      <div className="section-title">Explanation</div>
      <div className="explanation">{formatExplanation(r.explanation)}</div>

      <div className="section-title">Recommendation</div>
      <div className="recommendation">{r.recommendation}</div>

      <div className="reasoning-foot">
        <span>
          Evidence used: {r.corroboration_count ?? (r.evidence_ids || []).length} · Generated by
          reasoning engine
        </span>
        <span style={{ fontFamily: "var(--mono)", fontSize: 11 }}>
          four-way XGBoost · log evidence
        </span>
      </div>
    </div>
  );
}
